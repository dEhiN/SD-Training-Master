# string

# give the variable a string value
my_str = "Hello World!"

# convert the string to upper case using upper()
print(my_str.upper())

# convert the string to lower case using lower()
print(my_str.lower())

my_str = "  Hello World!  "
print(my_str)

# # remove whitespace from string using strip method
print(my_str.strip())

my_str = "Hello World!"

# replace item in string (all instances)
print(my_str.replace("Hello", "test"))

