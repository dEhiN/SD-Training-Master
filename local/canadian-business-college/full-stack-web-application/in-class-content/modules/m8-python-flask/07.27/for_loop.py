my_fruits_list = ["orange", "mango", "kiwi", "pineapple", "banana"]

# for loop
for fruit in my_fruits_list:
    print("the name of the fruit is - " + fruit)
    if fruit == "kiwi":
        # break keyword to terminate the loop
        break

# python for loop

my_fruits_list = ["orange", "mango", "kiwi", "pineapple", "banana"]

# for loop
for fruit in my_fruits_list:
    if fruit == "kiwi":
        # continue keyword to skip the loop
        continue
    print("the name of the fruit is - " + fruit)
