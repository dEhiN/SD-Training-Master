# python conditional operators

my_var = 1000

# if statement
if my_var < 200:
    print("inside if statement")
    print("true")
    print("still inside if statement")

print("hello from outside of the if statement")

# python conditional operators

my_var = 1000

# if else statement
if my_var < 200:
    print("inside if statement")
    print("true")
    print("still inside if statement")
else:
    print("inside else statement")
    print("false")

print("hello from outside of the if statement")

# python conditional operators

my_var = 1000

# # if else statement with elif to add checking of more conditions
if my_var < 200:
    print("my_var less than 200")
elif my_var > 200:
    print("my_var greater than 200")
else:
    print("inside else statement")

print("hello from outside of the if statement")

