# Logical operators

Total_cost = 1200

food_cost = 1000

water_cost = 200

# and operator (true only when both conditions are true)
print((Total_cost < food_cost) and (food_cost < water_cost))

Total_cost = 1200

food_cost = 1000

water_cost = 200

# or operator (false only when both conditions are false)
print((Total_cost > food_cost) or (food_cost < water_cost))
