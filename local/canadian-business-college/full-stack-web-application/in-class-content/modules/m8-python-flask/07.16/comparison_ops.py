# comparison operators

Total_cost = 1000

food_cost = 20

# find equal
print(Total_cost == food_cost)

# find not equal
print(Total_cost != food_cost)

my_str = "hello"

my_s_str = "Hello"

# find equal
print(my_str == my_s_str)

print(my_str.__eq__(my_s_str))

