// function

// declare a function with parameters
function addition_function(number1, number2) {
    console.log(number1 + number2);
}

function subtraction_function(number1, number2) {
    console.log(number1 - number2);
}

function multiplication_function(number1, number2, number3) {
    console.log(number1 * number2 * number3);
}

// invoke/call the function with arguments
addition_function(10, 40);

addition_function(123, 34);

addition_function(50, 10);

subtraction_function(99, 9);

multiplication_function(10, 20, 5);