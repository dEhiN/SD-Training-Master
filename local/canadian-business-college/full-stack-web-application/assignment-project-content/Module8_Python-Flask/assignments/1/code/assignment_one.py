# This task is to work with strings. It takes a first and last name, combines
# them, and then prints the full name out in all caps as well as in all lower
# case.
first_name = "David"
last_name = "Watson"
full_name = first_name + " " + last_name
print("Task 2:")
print(full_name.upper())
print(full_name.lower(), end="\n\n")

