# string

# give the variable a string value
my_str = "Hello world!"

# Slice out substring from the main string
# start range is counted (1) but the end range is not (8-1)
print(my_str[1:8])

# Slice out substring from the main string
# default start range first item
print(my_str[:8])

# Slice out substring from the main string
# default end range last item
print(my_str[2:])